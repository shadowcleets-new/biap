package com.sc.biap.util

import android.content.Context
import android.util.Log
import com.sc.biap.data.DefaultDataRepository
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.util.UUID

/**
 * @file DriveImageStore.kt
 * @description Design photos, stored beside the data they belong to.
 *
 * WHY THIS REPLACED FIREBASE STORAGE:
 *   Photos used to live in Firebase Storage while the catalogue lived in Google Drive's
 *   appDataFolder. Two stores meant two authentication systems on two independent code
 *   paths: a photo had to clear Firebase Auth, then App Check, then Storage rules, then
 *   the bucket; the data only had to clear Google OAuth and Drive.
 *
 *   Across three separate restore tests the data came back perfectly every time and the
 *   photo never did, and each failure was in a different part of that second lane - an
 *   unregistered App Check token, then a token silently regenerated by clearing storage.
 *   Every one of them presented identically: the catalogue restored, the photo did not.
 *
 *   Putting the photo where the data already is deletes that entire lane. One account,
 *   one grant, one transport, one set of failure modes. A photo can no longer come back
 *   without its design or a design without its photo, because they travel together.
 *
 * HOW IT WORKS:
 *   Each version of a photo is one appDataFolder file named img_<designId>_<stamp>_<nonce>.enc,
 *   encrypted with the SAME AES-256-GCM sync key as the catalogue - which itself lives in
 *   Drive as sync_key.txt, so a reinstalled device recovers the key and can therefore read
 *   both its data and its photographs.
 *
 *   Photos are separate files rather than embedded in the catalogue JSON on purpose: inlining
 *   them would mean re-uploading every photograph in the business each time a single price
 *   changed.
 *
 *   Keys are write-once. Replacing a photo writes a NEW name and repoints the design's
 *   imageRef, so a failed upload can never destroy the photo a design still points at, and
 *   two people replacing the same photo cannot corrupt each other.
 *
 *   Images are uploaded as-is. No compression or re-encoding is applied.
 */
object DriveImageStore {

    private const val TAG = "DriveImageStore"
    private const val PREFIX = "img_"
    private const val SUFFIX = ".enc"

    /** Superseded versions kept per design before the oldest are removed. */
    const val VERSIONS_RETAINED = 5

    /** Decrypted photos fetched from Drive, kept so each one is downloaded once per device. */
    private const val CACHE_DIR = "cloud_images"

    /**
     * A fresh, never-reused name for a new version of a design's photo.
     * The time prefix orders versions; the random suffix removes any chance of collision
     * when two devices upload within the same millisecond.
     */
    fun newVersionKey(designId: String): String {
        val stamp = System.currentTimeMillis()
        val nonce = UUID.randomUUID().toString().take(8)
        return "$PREFIX${designId}_${stamp}_$nonce$SUFFIX"
    }

    /**
     * True for keys this store owns. Photos uploaded by the previous Firebase Storage
     * implementation used paths like "designs/<id>/<file>.jpg"; those objects are not in
     * Drive, so they are recognised and reported rather than being fetched and failing oddly.
     */
    fun isDriveKey(key: String): Boolean = key.startsWith(PREFIX) && key.endsWith(SUFFIX)

    /**
     * Encrypt [localFile] and upload it under [key]. Returns true on success.
     *
     * The caller must only repoint a design's imageRef AFTER this returns true - that
     * ordering is what guarantees a failed upload leaves the previous photo reachable.
     */
    suspend fun upload(context: Context, localFile: File, key: String): Boolean =
        withContext(Dispatchers.IO) {
            if (!localFile.exists()) {
                Log.w(TAG, "upload skipped, local file missing: ${localFile.name}")
                return@withContext false
            }
            val token = accessToken(context) ?: run {
                Log.w(TAG, "upload failed: no Drive access token (is the Google account connected?)")
                return@withContext false
            }
            return@withContext try {
                val syncKey = EncryptionUtils.getOrGenerateLocalSyncKey(context)
                val encrypted = EncryptionUtils.encryptBytes(localFile.readBytes(), syncKey)
                val fileId = driveManager(context).uploadBinaryFile(token, encrypted, key)
                if (fileId == null) {
                    Log.w(TAG, "upload failed for $key")
                    false
                } else {
                    Log.i(TAG, "uploaded $key (${encrypted.size / 1024} KB)")
                    true
                }
            } catch (e: Exception) {
                Log.w(TAG, "upload failed for $key: ${e.message}")
                false
            }
        }

    /**
     * The decrypted photo for [key] as a local file, downloading it once if needed.
     *
     * Returns null when it cannot be produced - no token, not found, or a decryption
     * failure - and the UI turns that into "photo unavailable, try again" rather than
     * pretending the design has no photograph.
     */
    suspend fun ensureLocal(context: Context, key: String): File? = withContext(Dispatchers.IO) {
        val cached = cachedFile(context, key)
        if (cached.exists() && cached.length() > 0) return@withContext cached

        if (!isDriveKey(key)) {
            Log.w(
                TAG,
                "$key was uploaded by the old Firebase Storage backend and is not in Drive. " +
                    "Re-attach the photo to move it across."
            )
            return@withContext null
        }

        val token = accessToken(context) ?: run {
            Log.w(TAG, "cannot fetch $key: no Drive access token")
            return@withContext null
        }

        return@withContext try {
            val manager = driveManager(context)
            val fileId = manager.searchFile(token, key) ?: run {
                Log.w(TAG, "cannot fetch $key: not present in appDataFolder")
                return@withContext null
            }
            val encrypted = manager.downloadBinaryFile(token, fileId) ?: run {
                Log.w(TAG, "cannot fetch $key: download failed")
                return@withContext null
            }
            val syncKey = EncryptionUtils.getOrGenerateLocalSyncKey(context)
            val plain = EncryptionUtils.decryptBytes(encrypted, syncKey)

            // Write to a temporary name first, then rename. A download interrupted halfway
            // must not leave a truncated file that later looks like a valid cache hit.
            cached.parentFile?.mkdirs()
            val temp = File(cached.parentFile, "${cached.name}.part")
            temp.writeBytes(plain)
            if (!temp.renameTo(cached)) {
                temp.copyTo(cached, overwrite = true)
                temp.delete()
            }
            Log.i(TAG, "fetched $key (${plain.size / 1024} KB)")
            cached
        } catch (e: Exception) {
            Log.w(TAG, "cannot fetch $key: ${e.message}")
            null
        }
    }

    /**
     * Prune a design's photo history to the newest [keep] superseded versions.
     *
     * [protectKeys] - every key the design currently points at - are NEVER deleted, however
     * old they are. Losing a live photo to a retention sweep would be far worse than keeping
     * extra files.
     *
     * THIS USED TO PROTECT ONE KEY, AND THAT BECAME A BUG THE MOMENT A DESIGN COULD HOLD
     * FIVE PHOTOGRAPHS. All versions of a design share the `img_<designId>_` prefix, so a
     * sweep sees every photo's history in one list, keeps the newest few by timestamp, and
     * deletes the rest. With one photo per design that is exactly right. With five, the
     * four the sweep was not told to protect are just old names in that list - and the first
     * upload after adding them would have deleted live photographs out of Drive, with only
     * the local copies left and nothing on screen to say what had happened.
     *
     * Best-effort and deliberately non-fatal: it runs after a successful upload and pointer
     * move, so a failure here leaves extra files behind but never breaks a design. Returns
     * the number of versions actually deleted.
     */
    suspend fun pruneToLatest(
        context: Context,
        designId: String,
        keep: Int = VERSIONS_RETAINED,
        protectKeys: Set<String> = emptySet(),
    ): Int = withContext(Dispatchers.IO) {
        return@withContext try {
            val token = accessToken(context) ?: return@withContext 0
            val manager = driveManager(context)
            val versions = manager.listFilesByPrefix(token, "$PREFIX${designId}_")
            val doomed = versionsToPrune(
                names = versions.map { it.name },
                keep = keep,
                protectNames = protectKeys,
            ).toSet()

            var deleted = 0
            for (file in versions.filter { it.name in doomed }) {
                // One stubborn file must not abort the sweep.
                if (manager.deleteFile(token, file.id)) {
                    deleted++
                    Log.i(TAG, "pruned old version ${file.name}")
                }
            }
            deleted
        } catch (e: Exception) {
            Log.w(TAG, "prune failed for $designId: ${e.message}")
            0
        }
    }

    /**
     * Which version names should go: the newest [keep] are retained and every name in
     * [protectNames] is spared, wherever it falls in the ordering.
     *
     * Pure and separately unit-tested: retention deletes real photographs, so the decision of
     * what dies is kept free of any I/O and verified independently of Drive. Names embed a
     * millisecond stamp, so lexical order is chronological order.
     *
     * Protected names are removed from the list BEFORE the newest [keep] are counted. Left in,
     * a design's five live photos would fill the retention window on their own and every
     * genuinely superseded version would survive forever - retention that quietly stops
     * retaining. [keep] means "this many old versions besides the ones still in use".
     */
    fun versionsToPrune(names: List<String>, keep: Int, protectNames: Set<String>): List<String> {
        if (keep <= 0) return emptyList()
        return names.sorted()
            .filterNot { it in protectNames }
            .dropLast(keep)
    }

    /** Where a fetched photo is kept once decrypted. */
    fun cachedFile(context: Context, key: String): File =
        File(File(context.filesDir, CACHE_DIR), key.removeSuffix(SUFFIX) + ".jpg")

    private fun driveManager(context: Context): GoogleDriveSyncManager =
        DefaultDataRepository.getInstance(context).driveSyncManager

    private suspend fun accessToken(context: Context): String? =
        DefaultDataRepository.getInstance(context).authManager.getAccessToken()
}
